import { execFile } from "node:child_process";
import { mkdir, readdir, realpath, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { promisify } from "node:util";
import { assertSafeTree, assertWithinRoot } from "./paths";
import type {
  HandoffGitOutcome,
  HandoffWriteResult,
  HandoffWriter,
  WriteHandoffRequest,
} from "./types";

/**
 * ─────────────────────────────────────────────────────────────────────────────
 * THE ONLY IMPURE FILE IN lib/export.
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * It decides NOTHING. Every path and every byte arrives already decided by
 * buildHandoff(); this file's entire job is to put them on a disk and run git
 * over the result. That split is what lets the whole feature be unit-tested
 * with no filesystem and no git binary — and it is why a content bug is
 * catchable in CI rather than in a founder's Downloads folder.
 *
 * The three things this file is allowed to have opinions about, because they
 * are irreducibly about the world and not about content:
 *   1. Refusing to write into a directory that already has something in it.
 *   2. Re-checking every resolved absolute path against the repo root.
 *   3. Reporting a git failure instead of throwing it away or throwing on it.
 */

const execFileAsync = promisify(execFile);

export class ExportWriteError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "ExportWriteError";
  }
}

/**
 * The commit author when the caller supplies none.
 *
 * A BOT IDENTITY ON PURPOSE. The commit was generated by a machine from a fact
 * store; attributing it to the founder's git identity would put their name on
 * text they did not write, in the one artefact — `git log` — that everybody
 * treats as a record of who wrote what.
 */
export const DEFAULT_COMMIT_AUTHOR = {
  name: "idea-check export",
  email: "export@idea-check.local",
} as const;

/**
 * Environment variables that REDIRECT git at another repository.
 *
 * If the export ever runs from inside a git hook, a `git rebase -x`, or a CI
 * step that exports these (hooks always do), then `git init` would succeed in
 * our new directory while `git add -A` staged our files into whatever repo
 * GIT_DIR points at — silently committing a founder's PRD into the application
 * repository. Stripped rather than trusted.
 */
const GIT_REDIRECTION_VARS = [
  "GIT_DIR",
  "GIT_WORK_TREE",
  "GIT_INDEX_FILE",
  "GIT_OBJECT_DIRECTORY",
  "GIT_ALTERNATE_OBJECT_DIRECTORIES",
  "GIT_COMMON_DIR",
  "GIT_NAMESPACE",
] as const;

/**
 * Config files that must not be consulted.
 *
 * `init.templateDir` in the user's GLOBAL config makes plain `git init` copy an
 * arbitrary `hooks/` directory into the repository it creates — a documented
 * initial-access technique, and one the founder may not even know is configured
 * (some corporate dotfile installers set it). Pointing both config paths at a
 * file that does not exist reduces the new repository to git's inert
 * `*.sample` hooks. Git treats a missing config file as an empty one, so this
 * is safe on Windows too, where `/dev/null` is not a path.
 */
const NO_CONFIG_FILE = "/dev/null";

/**
 * Where git is told to look for hooks: a path that cannot exist inside a
 * freshly created repository.
 *
 * SECOND LOCK on the same door as FORBIDDEN_SEGMENTS in paths.ts. The writer
 * puts every file on disk BEFORE `git init`, and `git init` preserves a
 * `.git/hooks/` that is already there — so a tree entry at
 * `.git/hooks/post-commit` would execute during our own first commit.
 * `--no-verify` does NOT cover `post-commit`. paths.ts refuses to generate such
 * a path; this makes it inert even if one ever gets through.
 */
const NO_HOOKS_PATH = ".idea-check-export-hooks-disabled";

/**
 * Wall-clock ceiling for any single git invocation.
 *
 * Without it a credential helper waiting on an SSO prompt hangs forever, and if
 * the export ever runs inside a request handler that is a leaked invocation
 * rather than a slow one.
 */
const GIT_TIMEOUT_MS = 30_000;

function gitEnv(): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = { ...process.env };
  for (const key of GIT_REDIRECTION_VARS) {
    delete env[key];
  }
  env.GIT_CONFIG_GLOBAL = NO_CONFIG_FILE;
  env.GIT_CONFIG_SYSTEM = NO_CONFIG_FILE;
  // Never block on a credential or passphrase prompt: this may run inside a
  // request handler, where a blocked child process is an indefinite hang.
  env.GIT_TERMINAL_PROMPT = "0";
  env.GIT_ASKPASS = "";
  return env;
}

function errorText(error: unknown): string {
  if (error instanceof Error) {
    // execFile rejects with an Error carrying stderr; the stderr is the part a
    // human can act on ("git: command not found", "gpg failed to sign").
    const stderr = (error as { stderr?: unknown }).stderr;
    const detail = typeof stderr === "string" ? stderr.trim() : "";
    return detail.length > 0
      ? `${error.message.trim()}: ${detail}`
      : error.message;
  }
  return String(error);
}

/**
 * Run one git command with an ARGV ARRAY — never a shell string.
 *
 * `execFile` does not spawn a shell, so a commit message, a path or a project
 * name containing `;`, backticks or `$(...)` is a plain argument and nothing
 * else. Every value that reaches here has already passed through slugification
 * or is a generated constant, but argv-not-shell is the property that makes
 * that belt-and-braces rather than the only line of defence.
 */
async function git(cwd: string, args: string[]): Promise<string> {
  const { stdout } = await execFileAsync(
    "git",
    // Hardening applied to EVERY invocation, not just the commit. All of these
    // are compile-time literals: a `-c` KEY is the injection surface, not its
    // value — `core.fsmonitor`, `core.pager`, `credential.helper`, `alias.*`
    // and friends all make git execute a command — so no `-c` may ever be
    // built from data.
    ["-c", `core.hooksPath=${NO_HOOKS_PATH}`, ...args],
    {
      cwd,
      env: gitEnv(),
      timeout: GIT_TIMEOUT_MS,
      // A generated repo is small; anything approaching this is a bug, not data.
      maxBuffer: 4 * 1024 * 1024,
    }
  );
  return stdout.trim();
}

/**
 * `git init` + first commit.
 *
 * NEVER THROWS. By the time this runs the files are already on disk and are the
 * thing the founder actually wanted; git is a convenience on top. Every failure
 * mode here is environmental and none of them should cost the founder their
 * documents:
 *   • git not installed at all
 *   • `commit.gpgsign = true` globally with no key available in this context
 *   • no `user.email` configured (hence the explicit -c overrides)
 *   • a corporate `core.hooksPath` with a failing pre-commit hook
 *
 * Reported as a discriminated outcome so the caller can say what went wrong
 * instead of showing a boolean the founder cannot act on.
 */
async function initAndCommit(
  repoDir: string,
  message: string,
  author: { name: string; email: string }
): Promise<HandoffGitOutcome> {
  const branch = "main";
  try {
    // NOT `git init -b main`: `-b` needs git >= 2.28 and ERRORS OUT below it,
    // which would turn "your git is old" into "your export has no repository".
    // `-c` is the graceful form — git silently ignores config it does not know,
    // and symbolic-ref then makes the branch name true on every version.
    await git(repoDir, [
      "-c",
      `init.defaultBranch=${branch}`,
      "init",
      "--quiet",
    ]);
    await git(repoDir, ["symbolic-ref", "HEAD", `refs/heads/${branch}`]);
    // `--` before the pathspec. `.` is a literal here so it changes nothing
    // today; the habit belongs at the seam, because the day a path becomes a
    // variable is the day `--upload-pack=…` becomes a flag instead of a file.
    await git(repoDir, ["add", "--all", "--", "."]);
    await git(repoDir, [
      "-c",
      `user.name=${author.name}`,
      "-c",
      `user.email=${author.email}`,
      // A founder with global commit signing and no key in this context would
      // otherwise get a repo with files, no commit, and no explanation.
      "-c",
      "commit.gpgsign=false",
      "-c",
      "tag.gpgsign=false",
      "commit",
      "--quiet",
      "--no-verify",
      // `whitespace`, explicitly. The other mode git might pick, `strip`,
      // DELETES every line beginning with `#` — and a generated message is one
      // template edit away from containing a Markdown heading.
      "--cleanup=whitespace",
      "--message",
      message,
    ]);
    const sha = await git(repoDir, ["rev-parse", "HEAD"]);
    return { status: "committed", sha, branch };
  } catch (error) {
    return { status: "failed", reason: errorText(error) };
  }
}

/**
 * Refuse to write into a directory that already contains anything.
 *
 * FAIL-CLOSED. `overwrite` widens this to "write into a non-empty directory";
 * it never means "delete what is there". Nothing in lib/export unlinks a file,
 * because the blast radius of a wrong `repoName` combined with a recursive
 * delete is somebody's home directory.
 */
async function assertWritableRepoDir(
  repoDir: string,
  overwrite: boolean
): Promise<void> {
  let entries: string[];
  try {
    entries = await readdir(repoDir);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      return;
    }
    throw error;
  }
  if (entries.length > 0 && !overwrite) {
    throw new ExportWriteError(
      `Refusing to export into "${repoDir}": the directory already contains ${entries.length} entr${entries.length === 1 ? "y" : "ies"}. Pass overwrite: true to write into it anyway (nothing is ever deleted).`
    );
  }
}

/**
 * Write one file WITHOUT following a symlink at the final component.
 *
 * `writeFile` with the default `'w'` flag FOLLOWS a symlink and writes to its
 * target. Plant `repo/PRD.md -> /home/founder/.ssh/authorized_keys` and the
 * export happily fills it in. `'wx'` (O_CREAT|O_EXCL) refuses to open anything
 * that already exists, symlink included, which turns that attack into an
 * EEXIST.
 *
 * `overwrite` then has to mean something precise: UNLINK the existing entry and
 * create it fresh. Unlinking a symlink removes the LINK, never the target — so
 * overwriting stays safe, and the file we end up writing is unambiguously ours.
 * This is the only place in lib/export that removes anything, it removes one
 * named file at a time, and it never recurses.
 */
async function writeFileNoFollow(
  absolute: string,
  contents: string,
  overwrite: boolean
): Promise<void> {
  try {
    await writeFile(absolute, contents, { encoding: "utf8", flag: "wx" });
    return;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EEXIST") {
      throw error;
    }
    if (!overwrite) {
      throw new ExportWriteError(
        `Refusing to overwrite "${absolute}": it already exists. Pass overwrite: true to replace it.`
      );
    }
  }
  await rm(absolute, { force: true });
  await writeFile(absolute, contents, { encoding: "utf8", flag: "wx" });
}

/**
 * THE SEAM IMPLEMENTATION. Production passes this to runHandoff(); tests pass a
 * closure that records the request and never touches a disk.
 */
export function createNodeHandoffWriter(): HandoffWriter {
  return async (request: WriteHandoffRequest): Promise<HandoffWriteResult> => {
    const { plan, targetDir } = request;

    if (!targetDir || targetDir.trim().length === 0) {
      throw new ExportWriteError("Refusing to export: no target directory.");
    }

    // Third layer of path defence (slugification and assertSafeTree are the
    // other two). Cheap, and the layer that would still hold if a future change
    // let an un-slugified name through the first two.
    assertSafeTree(plan.files);

    const overwrite = request.overwrite === true;
    const root = resolve(targetDir);
    const repoDir = assertWithinRoot(root, join(root, plan.repoName));

    await assertWritableRepoDir(repoDir, overwrite);
    // The PARENT is created recursively; the repo directory itself is not, so
    // that a pre-existing `repoDir` symlink pointing somewhere else fails with
    // EEXIST instead of being silently followed. On the overwrite path it may
    // legitimately exist already, and assertWritableRepoDir has vetted it.
    await mkdir(root, { recursive: true });
    try {
      await mkdir(repoDir);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EEXIST" || !overwrite) {
        throw error;
      }
    }

    const realRepoDir = await realpath(repoDir);

    const written: string[] = [];
    for (const file of plan.files) {
      // Re-resolve and re-check EVERY file against the repo root. assertSafeTree
      // validated the string; this validates the path the syscall will get after
      // the platform has normalised it. A `..` that survived both would have to
      // beat an allow-list and a prefix check on the resolved path.
      const absolute = assertWithinRoot(repoDir, join(repoDir, file.path));
      await mkdir(dirname(absolute), { recursive: true });
      // FOURTH LAYER, and the only one that sees SYMLINKS. Every check above is
      // string arithmetic, and a string is blind to a link: with
      // `repo/docs -> /etc`, `repo/docs/x.md` passes every containment test ever
      // written and still lands in /etc. Resolving the PARENT after creating it
      // is what makes containment true of the inode rather than of the name.
      assertWithinRoot(realRepoDir, await realpath(dirname(absolute)));
      await writeFileNoFollow(absolute, file.contents, overwrite);
      written.push(file.path);
    }

    const gitOutcome = await initAndCommit(
      repoDir,
      plan.commitMessage,
      request.author ?? DEFAULT_COMMIT_AUTHOR
    );

    return { repoDir, written, git: gitOutcome };
  };
}
