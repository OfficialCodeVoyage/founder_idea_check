import assert from "node:assert/strict";
import { describe, it } from "vitest";
import {
  fileRequestFromUrl,
  fileUrlInChat,
  getFileImageProps,
  isFileStorageKey,
  keyFromFileUrl,
  ownerTagFromFileKey,
} from "./file-url";

const TAGGED_KEY = "Ab3_xY9-kLmN0pQr.l_u0a2bkphKLFKsBI4q5Tue9.png";
const LEGACY_KEY = "l_u0a2bkphKLFKsBI4q5Tue9.png";
const CHAT_ID = "00000000-0000-4000-8000-000000000001";

describe("isFileStorageKey", () => {
  it("recognizes only keys generated by the Files SDK integration", () => {
    assert.equal(isFileStorageKey(TAGGED_KEY), true);
    // Pre-tag keys are still managed: chats that hold them keep working.
    assert.equal(isFileStorageKey(LEGACY_KEY), true);
    assert.equal(isFileStorageKey("legacy-upload-name.png"), false);
    assert.equal(isFileStorageKey("folder/legacy-upload.png"), false);
  });

  it("reads an owner tag only from a tagged key", () => {
    assert.equal(ownerTagFromFileKey(TAGGED_KEY), "Ab3_xY9-kLmN0pQr");
    assert.equal(ownerTagFromFileKey(LEGACY_KEY), null);
  });
});

describe("chat-scoped file links", () => {
  it("adds the chat to a stored link for display only", () => {
    const stored = `/api/files/content?key=${TAGGED_KEY}`;
    const shown = fileUrlInChat(stored, CHAT_ID);
    assert.equal(
      shown,
      `/api/files/content?key=${encodeURIComponent(TAGGED_KEY)}&chatId=${CHAT_ID}`
    );
    // A display link is not a stored link.
    assert.equal(keyFromFileUrl(shown), null);
    assert.deepEqual(fileRequestFromUrl(shown), {
      key: TAGGED_KEY,
      chatId: CHAT_ID,
    });
    assert.equal(
      fileUrlInChat("https://example.com/a.png", CHAT_ID),
      "https://example.com/a.png"
    );
  });

  it("rejects a chat id that is not a uuid or extra parameters", () => {
    assert.equal(
      fileRequestFromUrl(`/api/files/content?key=${TAGGED_KEY}&chatId=x`),
      null
    );
    assert.equal(
      fileRequestFromUrl(
        `/api/files/content?key=${TAGGED_KEY}&chatId=${CHAT_ID}&a=b`
      ),
      null
    );
  });
});

describe("getFileImageProps", () => {
  it("makes managed worktree files same-origin for Next Image", () => {
    assert.deepEqual(
      getFileImageProps(
        "http://localhost:3030/api/files/content?key=Ab3_xY9-kLmN0pQr.l_u0a2bkphKLFKsBI4q5Tue9.png"
      ),
      {
        src: "/api/files/content?key=Ab3_xY9-kLmN0pQr.l_u0a2bkphKLFKsBI4q5Tue9.png",
        unoptimized: true,
      }
    );
  });

  it("leaves external images unchanged", () => {
    const url = "https://example.com/image.png";
    assert.deepEqual(getFileImageProps(url), { src: url, unoptimized: false });
  });
});
